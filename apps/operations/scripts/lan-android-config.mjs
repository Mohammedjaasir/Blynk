// LAN test only: writes the network policy for the `lanTest` Android build
// type, allowing plain http to ONE private LAN IPv4 (a development backend on
// a PC on the same Wi-Fi). The file goes to app/src/lanTest/, which is
// git-ignored, so a developer's address can never be committed. The
// production policy in app/src/main/ stays HTTPS-only and is not touched.
//
// Usage (PowerShell or bash):
//   CAP_LAN_HTTP=1 LAN_API_HOST=192.168.1.50 node scripts/lan-android-config.mjs
//   then: CAP_LAN_HTTP=1 npx cap sync android && cd android && ./gradlew assembleLanTest
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

function fail(message) {
  console.error(`lan-android-config: ${message}`);
  process.exit(1);
}

if (process.env.CAP_LAN_HTTP !== '1') {
  fail('refusing to run: set CAP_LAN_HTTP=1 to build a LAN test APK on purpose.');
}

const host = (process.env.LAN_API_HOST ?? '').trim();

/** Canonical dotted-decimal IPv4 in 10/8, 172.16/12 or 192.168/16 only. */
function isPrivateLanIpv4(value) {
  const parts = value.split('.');
  if (parts.length !== 4) return false;
  const bytes = [];
  for (const part of parts) {
    if (!/^(0|[1-9][0-9]{0,2})$/.test(part)) return false;
    const n = Number(part);
    if (n > 255) return false;
    bytes.push(n);
  }
  if (bytes[0] === 10) return !(bytes[1] === 0 && (bytes[2] === 2 || bytes[2] === 3) && bytes[3] === 2);
  if (bytes[0] === 172) return bytes[1] >= 16 && bytes[1] <= 31;
  return bytes[0] === 192 && bytes[1] === 168;
}

if (!isPrivateLanIpv4(host)) {
  fail(`LAN_API_HOST must be a private LAN IPv4 (10.x, 172.16-31.x, 192.168.x), got "${host}".`);
}

const out = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'android',
  'app',
  'src',
  'lanTest',
  'res',
  'xml',
  'network_security_config.xml',
);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/lan-android-config.mjs for the lanTest build type.
     Git-ignored. Plain http to ${host} only; everything else HTTPS. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">${host}</domain>
    </domain-config>
</network-security-config>
`,
);
console.log(`lan-android-config: wrote lanTest policy allowing http to ${host} -> ${out}`);
